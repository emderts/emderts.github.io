import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' }); const p = await b.newPage({ viewport: { width: 1400, height: 1000 } });
const errs = []; p.on('pageerror', e => errs.push(e.message));
await p.goto('file://' + process.cwd() + '/dist/mnestis.html');
await p.click('button.primary'); await p.waitForTimeout(400);
await p.evaluate(() => { const g = window.__game; g.board.placeLab('t1', 'I', g.constructor && { cells: [], edges: [] }); });
await p.evaluate(() => { const g = window.__game; g.placeLabyrinth(g.titans[1], 'Z'); });
await p.waitForTimeout(300);
const btns = await p.$$('#prompt button'); if (btns[3]) await btns[3].hover(); await p.waitForTimeout(200);
await p.screenshot({ path: 'test/shot-lab1.png' });
if (btns[3]) await btns[3].click(); await p.waitForTimeout(200);
await p.evaluate(() => { const g = window.__game; g.placeLabyrinth(g.titans[0], 'O'); }); await p.waitForTimeout(200);
const b2 = await p.$$('#prompt button'); if (b2[0]) await b2[0].click(); await p.waitForTimeout(300);
await p.screenshot({ path: 'test/shot-lab2.png' });
console.log('errors', errs); await b.close();
